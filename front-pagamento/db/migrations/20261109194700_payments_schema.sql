CREATE UNIQUE INDEX IF NOT EXISTS products_ref_key ON payments.products (ref);
CREATE UNIQUE INDEX IF NOT EXISTS discount_coupons_code_upper_idx ON payments.discount_coupons (upper(trim(code)));
CREATE UNIQUE INDEX IF NOT EXISTS prices_ref_key ON payments.prices (ref);
CREATE UNIQUE INDEX IF NOT EXISTS profiles_email_key ON payments.profiles (email);
CREATE UNIQUE INDEX IF NOT EXISTS admin_users_email_key ON payments.admin_users (email);
CREATE INDEX IF NOT EXISTS orders_user_created_at_idx ON payments.orders (user_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS webhook_events_provider_event_id_key ON payments.webhook_events (provider, provider_event_id) WHERE provider_event_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS asaas_payments_dedup_idx ON payments.asaas_payments (asaas_payment_id) WHERE asaas_payment_id IS NOT NULL;

