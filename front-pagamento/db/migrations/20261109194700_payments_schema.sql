CREATE SCHEMA IF NOT EXISTS payments;

CREATE OR REPLACE FUNCTION payments.update_updated_at_column()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

